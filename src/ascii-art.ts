function validate(char: string, shape: readonly string[]): Glyph {
    if (shape.length !== HEIGHT) {
        throw new Error(`Glyph ${JSON.stringify(char)} has ${shape.length} rows, expected ${HEIGHT}`);
    }

    const width = shape[0]!.length;

    for (const [i, row] of shape.entries()) {
        if (row.length !== width) {
            throw new Error(`Glyph ${JSON.stringify(char)} row ${i} is ${row.length} wide, expected ${width}`);
        }
    }

    return shape;
}

// Indexed by char code; `null` means "no glyph" (control characters, DEL, the
// punctuation the font leaves blank, and anything outside 7-bit ASCII).
const characters: (Glyph | null)[] = Array.from({ length: 128 }, () => null);

for (const [char, shape] of Object.entries(shapes)) {
    characters[char.charCodeAt(0)] = validate(char, shape);
}

// Lowercase letters reuse the uppercase glyphs — the font draws them identically.
for (let code = "A".charCodeAt(0); code <= "Z".charCodeAt(0); code++) {
    characters[code + 32] = characters[code]!;
}

export const art = {
    characters: characters as readonly (Glyph | null)[],
} as const;
