// FIGfont "ANSI Shadow" (see tmp/fonts/ansi-shadow.flf), transcribed into a
// plain lookup table.
//
// The glyphs are proportional, not a fixed-cell bitmap: every glyph is exactly
// HEIGHT rows tall, but each one carries its own width, so callers must advance
// the cursor by the width of the glyph they just drew rather than by a shared
// constant. Rows are stored verbatim — the box-drawing characters are the art
// itself, so there is no ink placeholder to substitute.
//
// The font leaves ten printable code points blank — quote, apostrophe, plus,
// equals, backslash, backtick, both braces and the pipe, and tilde — so they
// stay `null` here alongside the control characters.

const HEIGHT = 7;

